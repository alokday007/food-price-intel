"""Render the README's generated blocks: the scoreboard and "Models evaluated".

Both are generated, never typed: this command rewrites everything between each
pair of marker comments from a committed artifact.

* scoreboard — from ``data/seed/scoreboard.json`` (written by
  ``evaluate_sarima --summarize --out``); changes every monthly refresh.
* models — from ``data/eval/lgbm_9a.json`` (written by ``evaluate_lgbm``) plus
  the 9a.1 column and verdict from ``data/eval/lgbm_9a1.json`` (written by
  ``evaluate_lgbm_9a1``); one-off experiments that are NOT refreshed. It uses
  those files' own eval_end and their own naive_1/SARIMA numbers, never the live
  scoreboard's, so a refresh that moves the scoreboard leaves this block (and
  its check) untouched.

``--check`` only compares, and fails if either block is stale — the test suite
runs the same comparison, so a refresh that forgets this step goes red.
"""

from __future__ import annotations

import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from apps.forecasting.display import format_delta_pct
from apps.forecasting.views import SCOREBOARD_PATH, SERIES_LABELS

README_PATH = Path(settings.BASE_DIR) / "README.md"
LGBM_PATH = Path(settings.BASE_DIR) / "data" / "eval" / "lgbm_9a.json"
LGBM_9A1_PATH = Path(settings.BASE_DIR) / "data" / "eval" / "lgbm_9a1.json"
PREREG_9A1 = "docs/experiments/9a1_prereg.md"
START = "<!-- scoreboard:start (generated by `manage.py render_scoreboard`; do not edit) -->"
END = "<!-- scoreboard:end -->"
MODELS_START = "<!-- models:start (generated by `manage.py render_scoreboard`; do not edit) -->"
MODELS_END = "<!-- models:end -->"

VERDICT_WORDS = {"BEATS": "beats", "TIES": "ties", "LOSES": "loses to"}
HORIZON_WORDS = {"1": "1 month", "3": "3 months"}

# Phase 9a models then the 9a.1 variant, in table order:
# (key in the row's ``mae``, name, what it is, deployed?)
MODELS = (
    ("naive_1", "No-change baseline (`naive_1`)", "next month = this month", "yes"),
    ("sarima", "SARIMA(1,1,1)(1,1,1,12)", "seasonal ARIMA, same order on every series", "yes"),
    ("lgbm_series", "LightGBM per-series", "gradient-boosted trees, one model per series", "no"),
    ("lgbm_pooled", "LightGBM pooled", "one model across all 6 series, series as a feature", "no"),
    (
        "lgbm_pooled_pct",
        "LightGBM pooled, log-change target (9a.1)",
        "as LightGBM pooled, but predicts the log change (scale-free across series)",
        "no",
    ),
)
SHORT_NAMES = {
    "naive_1": "no-change",
    "sarima": "SARIMA",
    "lgbm_series": "LGBM-series",
    "lgbm_pooled": "LGBM-pooled",
    "lgbm_pooled_pct": "LGBM-pooled-log",
}
NEW_9A1 = "lgbm_pooled_pct"  # the one model lgbm_9a1.json adds


def render_block(scoreboard: dict) -> str:
    """The markdown between the markers (exclusive), from a scoreboard payload."""
    model = scoreboard["model"]
    order = f"SARIMA{tuple(model['order'])}{tuple(model['seasonal_order'])}".replace(" ", "")
    tie_pct = f"{scoreboard['tie_threshold']:.0%}"
    lines = [
        f"Evaluated through **{scoreboard['eval_end']}** — expanding-window walk-forward from "
        f"{scoreboard['initial_train_end']}, {order} vs the no-change baseline (`naive_1`) "
        f"on identical folds. *Ties* = MAEs within {tie_pct} of each other.",
        "",
        "| series | horizon | folds | SARIMA MAE | no-change MAE | Δ | SARIMA … |",
        "|---|---|---|---|---|---|---|",
    ]
    counts = {"BEATS": 0, "TIES": 0, "LOSES": 0}
    for code, horizons in scoreboard["groups"].items():
        for h, row in horizons.items():
            counts[row["verdict"]] += 1
            lines.append(
                f"| {SERIES_LABELS.get(code, code)} | {HORIZON_WORDS.get(h, h + ' months')} "
                f"| {row['folds']} | {row['sarima_mae']:.3f} | {row['naive_1_mae']:.3f} "
                f"| {format_delta_pct(row['rel_delta'])} | **{VERDICT_WORDS[row['verdict']]}** the baseline |"
            )
    lines += [
        "",
        f"**Totals ({sum(counts.values())} series × horizons):** SARIMA beats the baseline "
        f"{counts['BEATS']}, ties {counts['TIES']}, loses {counts['LOSES']}.",
    ]
    return "\n".join(lines)


def lgbm_rows(lgbm: dict):
    """(series code, horizon key, row) for every series × horizon in lgbm_9a.json."""
    for code, horizons in lgbm["groups"].items():
        for h, row in horizons.items():
            yield code, h, row


def _fold_count(lgbm: dict, h: str) -> int:
    """The one fold count at horizon ``h`` — identical on every series, or fail."""
    counts = {row["folds"] for _, rh, row in lgbm_rows(lgbm) if rh == h}
    if len(counts) != 1:
        raise CommandError(f"lgbm_9a.json: horizon {h} has fold counts {sorted(counts)}.")
    return counts.pop()


def model_rows(lgbm: dict, lgbm_9a1: dict):
    """Every lgbm_9a.json row with the 9a.1 model merged in, as
    (series code, horizon key, mae, verdict vs naive_1, rel. delta vs naive_1, best).

    The two files must describe the same evaluation: same eval_end, same rows and
    fold counts, and the 9a comparators 9a.1 copied must be identical.
    """
    if lgbm_9a1["eval_end"] != lgbm["eval_end"]:
        raise CommandError(
            f"lgbm_9a1.json eval_end {lgbm_9a1['eval_end']} != lgbm_9a.json {lgbm['eval_end']}."
        )
    for code, h, row in lgbm_rows(lgbm):
        new = lgbm_9a1["groups"].get(code, {}).get(h)
        if new is None or new["folds"] != row["folds"]:
            raise CommandError(f"lgbm_9a1.json: {code} H={h} missing or on different folds.")
        mae = {key: row["mae"][key] for key, *_ in MODELS if key != NEW_9A1}
        if any(new["mae"][key] != v for key, v in mae.items()):
            raise CommandError(f"lgbm_9a1.json: {code} H={h} comparator MAEs differ from lgbm_9a.json.")
        mae[NEW_9A1] = new["mae"][NEW_9A1]
        verdicts = {**row["verdict_vs_naive_1"], NEW_9A1: new["verdict_vs_naive_1"]}
        rel = {**row["rel_delta_vs_naive_1"], NEW_9A1: new["rel_delta_vs_naive_1"]}
        yield code, h, mae, verdicts, rel, min(mae, key=mae.get)


def count_verdicts(lgbm: dict, lgbm_9a1: dict) -> dict[str, dict[str, int]]:
    """Per model, BEATS/TIES/LOSES vs naive_1, counted from the per-row verdicts."""
    counts = {key: {"BEATS": 0, "TIES": 0, "LOSES": 0} for key, *_ in MODELS if key != "naive_1"}
    for *_, verdicts, _, _ in model_rows(lgbm, lgbm_9a1):
        for model, v in verdicts.items():
            counts[model][v] += 1
    return counts


def count_best(lgbm: dict, lgbm_9a1: dict) -> dict[str, int]:
    """Per model, the number of series × horizon rows where it has the lowest MAE
    of all five."""
    counts = {key: 0 for key, *_ in MODELS}
    for *_, best in model_rows(lgbm, lgbm_9a1):
        counts[best] += 1
    return counts


def closing_line_9a1(lgbm_9a1: dict) -> str:
    """The number-free 9a.1 outcome, chosen by the file's own pre-registered verdict."""
    verdict = lgbm_9a1["decision"]["verdict"]
    if verdict != "FAILURE":
        raise CommandError(f"lgbm_9a1.json verdict is {verdict}; the README only words FAILURE.")
    return (
        f"A single [pre-registered]({PREREG_9A1}) variant with a scale-free target was "
        "tested and failed its decision rule; the LightGBM line of work is closed."
    )


def render_models_block(lgbm: dict, lgbm_9a1: dict) -> str:
    """The markdown between the models markers (exclusive), from lgbm_9a.json and
    lgbm_9a1.json only."""
    n_rows = sum(1 for _ in lgbm_rows(lgbm))
    verdicts = count_verdicts(lgbm, lgbm_9a1)
    best = count_best(lgbm, lgbm_9a1)
    lines = [
        f"Evaluated through **{lgbm['eval_end']}** on the same walk-forward folds as the scoreboard "
        f"({_fold_count(lgbm, '1')} at 1 month, {_fold_count(lgbm, '3')} at 3 months). "
        "One-off experiment; not re-run in the monthly refresh.",
        "",
        "| model | what it is | deployed? |",
        "|---|---|---|",
    ]
    lines += [f"| {name} | {what} | {deployed} |" for _, name, what, deployed in MODELS]
    lines += [
        "",
        "| model | beats | ties | loses | best model in |",
        "|---|---|---|---|---|",
    ]
    for key, name, _, _ in MODELS:
        v = verdicts.get(key)
        cells = "— | — | —" if v is None else f"{v['BEATS']} | {v['TIES']} | {v['LOSES']}"
        lines.append(f"| {name} | {cells} | {best[key]} of {n_rows} rows |")
    lines += [
        "",
        "*Beats / ties / loses* are vs the no-change baseline, with the scoreboard's tie rule. "
        "MAE per row (lowest in **bold**; Δ is the best model vs the baseline):",
        "",
        "| series | horizon | " + " | ".join(SHORT_NAMES[key] for key, *_ in MODELS) + " | best |",
        "|---|---|" + "---|" * len(MODELS) + "---|",
    ]
    for code, h, raw, _, rel, best_key in model_rows(lgbm, lgbm_9a1):
        mae = {key: f"{v:.3f}" for key, v in raw.items()}
        mae[best_key] = f"**{mae[best_key]}**"
        winner = SHORT_NAMES[best_key]
        if best_key != "naive_1":
            winner += f" ({format_delta_pct(rel[best_key])})"
        lines.append(
            f"| {SERIES_LABELS.get(code, code)} | {HORIZON_WORDS.get(h, h + ' months')} "
            f"| {' | '.join(mae[key] for key, *_ in MODELS)} | {winner} |"
        )
    # Each bullet is asserted against lgbm_9a.json / lgbm_9a1.json in test_readme_models.py.
    lines += [
        "",
        "**What we learned**",
        "",
        "- LightGBM did not beat SARIMA on any row, and was never the best model on any row.",
        "- Pooling helped slightly: the pooled model had a lower MAE than the per-series model "
        "on more rows than the reverse.",
        "- The pooled model's most important feature at both horizons was last month's change "
        "(momentum) — the signal SARIMA's AR term on the monthly change already models.",
        f"- {closing_line_9a1(lgbm_9a1)}",
        "",
        "Method: fixed hyperparameters (no tuning); the 9a variants predict the change, not the "
        "level (forecast = last value + predicted change), and the 9a.1 variant predicts the log "
        "change (forecast = last value × exp(predicted log change)); direct multi-step (one model per horizon, "
        "refit every fold); leakage tests include cross-series poisoning of the pooled model. "
        "See [`lgbm.py`](apps/forecasting/lgbm.py), "
        "[`evaluate_lgbm.py`](apps/forecasting/management/commands/evaluate_lgbm.py) and "
        "[`test_lgbm_leakage.py`](apps/forecasting/tests/test_lgbm_leakage.py).",
    ]
    return "\n".join(lines)


def splice(readme: str, block: str, start: str = START, end: str = END) -> str:
    """Replace the content between a pair of markers; fail if they are missing."""
    try:
        head, rest = readme.split(start, 1)
        _, tail = rest.split(end, 1)
    except ValueError:
        raise CommandError(f"README is missing the markers:\n  {start}\n  {end}")
    return f"{head}{start}\n{block}\n{end}{tail}"


def splice_models(readme: str, lgbm: dict, lgbm_9a1: dict) -> str:
    return splice(readme, render_models_block(lgbm, lgbm_9a1), MODELS_START, MODELS_END)


class Command(BaseCommand):
    help = (
        "Regenerate the README scoreboard (from data/seed/scoreboard.json) and "
        "Models evaluated (from data/eval/lgbm_9a.json + lgbm_9a1.json) sections."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "--check",
            action="store_true",
            help="Don't write; exit with an error if README.md is out of date.",
        )

    def handle(self, *args, **options):
        scoreboard = json.loads(SCOREBOARD_PATH.read_text(encoding="utf-8"))
        lgbm = json.loads(LGBM_PATH.read_text(encoding="utf-8"))
        lgbm_9a1 = json.loads(LGBM_9A1_PATH.read_text(encoding="utf-8"))
        current = README_PATH.read_text(encoding="utf-8")

        if options["check"]:
            stale = [
                name
                for name, spliced in (
                    ("scoreboard", splice(current, render_block(scoreboard))),
                    ("models", splice_models(current, lgbm, lgbm_9a1)),
                )
                if spliced != current
            ]
            if stale:
                raise CommandError(
                    f"README {' and '.join(stale)} section stale — run `manage.py render_scoreboard`."
                )
            self.stdout.write(self.style.SUCCESS("README scoreboard and models sections are up to date."))
            return

        updated = splice_models(splice(current, render_block(scoreboard)), lgbm, lgbm_9a1)
        README_PATH.write_text(updated, encoding="utf-8")
        state = "updated" if updated != current else "already up to date"
        self.stdout.write(
            self.style.SUCCESS(
                f"README {state} (scoreboard eval_end {scoreboard['eval_end']}; "
                f"models eval_end {lgbm['eval_end']}, not refreshed)."
            )
        )
