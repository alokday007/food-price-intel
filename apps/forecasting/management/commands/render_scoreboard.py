"""Render the README scoreboard block from data/seed/scoreboard.json.

The README's scoreboard table is generated, never typed: this command rewrites
everything between the two marker comments from the committed scoreboard
artifact (itself written by ``evaluate_sarima --summarize --out``). ``--check``
only compares, and fails if the README is stale — the test suite runs the same
comparison, so a refresh that forgets this step goes red.
"""

from __future__ import annotations

import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from apps.forecasting.display import format_delta_pct
from apps.forecasting.views import SCOREBOARD_PATH, SERIES_LABELS

README_PATH = Path(settings.BASE_DIR) / "README.md"
START = "<!-- scoreboard:start (generated by `manage.py render_scoreboard`; do not edit) -->"
END = "<!-- scoreboard:end -->"

VERDICT_WORDS = {"BEATS": "beats", "TIES": "ties", "LOSES": "loses to"}
HORIZON_WORDS = {"1": "1 month", "3": "3 months"}


def render_block(scoreboard: dict) -> str:
    """The markdown between the markers (exclusive), from a scoreboard payload."""
    model = scoreboard["model"]
    order = f"SARIMA{tuple(model['order'])}{tuple(model['seasonal_order'])}".replace(" ", "")
    tie_pct = f"{scoreboard['tie_threshold']:.0%}"
    lines = [
        f"Evaluated through **{scoreboard['eval_end']}** — expanding-window walk-forward from "
        f"{scoreboard['initial_train_end']}, {order} vs the no-change baseline (`naive_1`) "
        f"on identical folds. *Ties* = MAEs within {tie_pct} of each other.",
        "",
        "| series | horizon | folds | SARIMA MAE | no-change MAE | Δ | SARIMA … |",
        "|---|---|---|---|---|---|---|",
    ]
    counts = {"BEATS": 0, "TIES": 0, "LOSES": 0}
    for code, horizons in scoreboard["groups"].items():
        for h, row in horizons.items():
            counts[row["verdict"]] += 1
            lines.append(
                f"| {SERIES_LABELS.get(code, code)} | {HORIZON_WORDS.get(h, h + ' months')} "
                f"| {row['folds']} | {row['sarima_mae']:.3f} | {row['naive_1_mae']:.3f} "
                f"| {format_delta_pct(row['rel_delta'])} | **{VERDICT_WORDS[row['verdict']]}** the baseline |"
            )
    lines += [
        "",
        f"**Totals ({sum(counts.values())} series × horizons):** SARIMA beats the baseline "
        f"{counts['BEATS']}, ties {counts['TIES']}, loses {counts['LOSES']}.",
    ]
    return "\n".join(lines)


def splice(readme: str, block: str) -> str:
    """Replace the content between the markers; fail if they are missing."""
    try:
        head, rest = readme.split(START, 1)
        _, tail = rest.split(END, 1)
    except ValueError:
        raise CommandError(f"README is missing the scoreboard markers:\n  {START}\n  {END}")
    return f"{head}{START}\n{block}\n{END}{tail}"


class Command(BaseCommand):
    help = "Regenerate the README scoreboard table from data/seed/scoreboard.json."

    def add_arguments(self, parser):
        parser.add_argument(
            "--check",
            action="store_true",
            help="Don't write; exit with an error if README.md is out of date.",
        )

    def handle(self, *args, **options):
        scoreboard = json.loads(SCOREBOARD_PATH.read_text(encoding="utf-8"))
        current = README_PATH.read_text(encoding="utf-8")
        updated = splice(current, render_block(scoreboard))

        if options["check"]:
            if updated != current:
                raise CommandError(
                    "README scoreboard is stale — run `manage.py render_scoreboard`."
                )
            self.stdout.write(self.style.SUCCESS("README scoreboard is up to date."))
            return

        README_PATH.write_text(updated, encoding="utf-8")
        state = "updated" if updated != current else "already up to date"
        self.stdout.write(
            self.style.SUCCESS(f"README scoreboard {state} (eval_end {scoreboard['eval_end']}).")
        )
