"""The README "Models evaluated" section must match data/eval/lgbm_9a.json and
data/eval/lgbm_9a1.json.

The section is generated by ``manage.py render_scoreboard`` from those two
artifacts alone. These tests pin three things: the README is not stale, the
number-free "What we learned" claims still hold against the JSON, and a monthly
refresh that moves scoreboard.json to a later eval_end breaks nothing here.
"""

from __future__ import annotations

import copy
import json
import re

import pytest
from django.core.management import call_command

from apps.forecasting.management.commands import render_scoreboard as rs
from apps.forecasting.management.commands.evaluate_lgbm_9a1 import decide
from apps.forecasting.views import SCOREBOARD_PATH


@pytest.fixture
def lgbm():
    return json.loads(rs.LGBM_PATH.read_text(encoding="utf-8"))


@pytest.fixture
def lgbm_9a1():
    return json.loads(rs.LGBM_9A1_PATH.read_text(encoding="utf-8"))


@pytest.fixture
def scoreboard():
    return json.loads(SCOREBOARD_PATH.read_text(encoding="utf-8"))


def test_readme_models_section_matches_artifact(lgbm, lgbm_9a1):
    readme = rs.README_PATH.read_text(encoding="utf-8")
    assert rs.splice_models(readme, lgbm, lgbm_9a1) == readme, (
        "README models section is stale — run `manage.py render_scoreboard`."
    )


def test_counts_in_code_agree_with_the_artifact_summary(lgbm, lgbm_9a1):
    """Counted from per-row verdicts/MAEs; must agree with the files' own totals."""
    assert rs.count_verdicts(lgbm, lgbm_9a1) == {
        **lgbm["totals"],
        rs.NEW_9A1: lgbm_9a1["totals_vs_naive_1"],
    }
    # Best of five: the 9a.1 model is never lowest, so the 9a counts stand.
    assert rs.count_best(lgbm, lgbm_9a1) == {**lgbm["best_counts"], rs.NEW_9A1: 0}


def test_9a1_comparators_mismatch_is_refused(lgbm, lgbm_9a1):
    bad = copy.deepcopy(lgbm_9a1)
    bad["groups"]["DAIRY"]["1"]["mae"]["sarima"] += 0.001
    with pytest.raises(rs.CommandError, match="comparator MAEs differ"):
        rs.render_models_block(lgbm, bad)


# --- "What we learned": each bullet, asserted against the JSON -----------------

LGBM = ("lgbm_series", "lgbm_pooled", rs.NEW_9A1)


def test_claim_lightgbm_never_beat_sarima_and_never_best(lgbm, lgbm_9a1):
    best = rs.count_best(lgbm, lgbm_9a1)
    assert all(best[m] == 0 for m in LGBM)
    for code, h, mae, *_ in rs.model_rows(lgbm, lgbm_9a1):
        for m in LGBM:
            assert mae[m] >= mae["sarima"], f"{code} H={h}: {m} beat SARIMA"


def test_claim_pooled_beats_per_series_on_more_rows_than_the_reverse(lgbm):
    rows = [row["mae"] for _, _, row in rs.lgbm_rows(lgbm)]
    pooled_wins = sum(r["lgbm_pooled"] < r["lgbm_series"] for r in rows)
    series_wins = sum(r["lgbm_series"] < r["lgbm_pooled"] for r in rows)
    assert pooled_wins > series_wins


def test_claim_last_months_change_is_the_top_pooled_feature(lgbm):
    for h, ranked in lgbm["pooled_importance_gain"].items():
        top = max(ranked, key=lambda r: r["gain_share"])
        assert top["feature"] == "chg_lag1", f"H={h}: top feature is {top['feature']}"


def test_claim_9a1_failed_its_decision_rule(lgbm, lgbm_9a1):
    """The 'failed its decision rule' line comes from the recorded verdict, and that
    verdict is what the pre-registered rule gives when re-applied to the rows."""
    assert lgbm_9a1["decision"]["verdict"] == "FAILURE"
    assert lgbm_9a1["preregistration"] == rs.PREREG_9A1
    rows = [
        {"row": f"{code} H={h}", "naive_1": mae["naive_1"], "sarima": mae["sarima"], "new": mae[rs.NEW_9A1]}
        for code, h, mae, *_ in rs.model_rows(lgbm, lgbm_9a1)
    ]
    assert decide(rows, lgbm_9a1["decision"]["sarima_losses"]) == lgbm_9a1["decision"]
    assert "failed its decision rule" in rs.render_models_block(lgbm, lgbm_9a1)

    flipped = copy.deepcopy(lgbm_9a1)
    flipped["decision"]["verdict"] = "SUCCESS"
    with pytest.raises(rs.CommandError, match="verdict is SUCCESS"):
        rs.render_models_block(lgbm, flipped)


def test_method_targets_match_the_artifacts(lgbm, lgbm_9a1):
    """The Method paragraph's per-variant targets are the ones each file recorded."""
    assert lgbm["design"]["target"] == "y[t+h] - y[t]; forecast = y[t] + predicted change"
    assert lgbm_9a1["design"]["target"] == (
        "log(y[t+h] / y[t]); forecast = y[t] * exp(predicted log change)"
    )
    method = rs.render_models_block(lgbm, lgbm_9a1).split("Method:", 1)[1]
    assert "the 9a variants predict the change, not the level" in method
    assert "the 9a.1 variant predicts the log change" in method
    # Number-free apart from the variant labels.
    unlabelled = re.sub(r"\]\([^)]*\)", "]", method).replace("9a.1", "").replace("9a", "")
    assert not any(c.isdigit() for c in unlabelled), unlabelled


def test_claims_are_number_free(lgbm, lgbm_9a1):
    block = rs.render_models_block(lgbm, lgbm_9a1)
    learned = block.split("**What we learned**", 1)[1].split("Method:", 1)[0]
    visible = re.sub(r"\]\([^)]*\)", "]", learned)  # link targets are paths, not claims
    assert not any(c.isdigit() for c in visible), visible


# --- Monthly refresh safety ---------------------------------------------------


def _later_scoreboard(scoreboard: dict) -> dict:
    """A scoreboard as a refresh one month on would write it: new eval_end, more
    folds, different naive_1/SARIMA numbers and a flipped verdict."""
    later = copy.deepcopy(scoreboard)
    later["eval_end"] = "2026-10"
    later["generated_at"] = "2026-11-05T10:00:00+00:00"
    for horizons in later["groups"].values():
        for row in horizons.values():
            row["folds"] += 1
            row["naive_1_mae"] = round(row["naive_1_mae"] * 1.03, 4)
            row["sarima_mae"] = round(row["sarima_mae"] * 0.97, 4)
            row["rel_delta"] = round(row["sarima_mae"] / row["naive_1_mae"] - 1, 5)
            row["verdict"] = "BEATS"
    return later


def test_refresh_to_later_eval_end_leaves_models_section_valid(
    scoreboard, lgbm, lgbm_9a1, tmp_path, monkeypatch
):
    """Simulate the monthly refresh: scoreboard.json moves on, lgbm_9a*.json do not.

    Run the real command (write, then --check) against temp copies; the models
    block must be byte-identical and every README check must still pass.
    """
    assert lgbm["eval_end"] == "2026-09"
    assert lgbm_9a1["eval_end"] == "2026-09"
    later = _later_scoreboard(scoreboard)
    readme = rs.README_PATH.read_text(encoding="utf-8")
    lgbm_before = rs.LGBM_PATH.read_text(encoding="utf-8")
    lgbm_9a1_before = rs.LGBM_9A1_PATH.read_text(encoding="utf-8")

    board_path = tmp_path / "scoreboard.json"
    board_path.write_text(json.dumps(later), encoding="utf-8")
    readme_path = tmp_path / "README.md"
    readme_path.write_text(readme, encoding="utf-8")
    monkeypatch.setattr(rs, "SCOREBOARD_PATH", board_path)
    monkeypatch.setattr(rs, "README_PATH", readme_path)

    call_command("render_scoreboard")
    refreshed = readme_path.read_text(encoding="utf-8")

    # The scoreboard moved on...
    assert refreshed != readme
    assert "Evaluated through **2026-10**" in refreshed
    assert rs.splice(refreshed, rs.render_block(later)) == refreshed
    # ...the models section did not, and still validates against the unchanged JSON.
    models = lambda text: text.split(rs.MODELS_START, 1)[1].split(rs.MODELS_END, 1)[0]  # noqa: E731
    assert models(refreshed) == models(readme)
    assert "Evaluated through **2026-09** on the same walk-forward folds" in models(refreshed)
    assert "failed its decision rule" in models(refreshed)
    assert rs.splice_models(refreshed, lgbm, lgbm_9a1) == refreshed
    call_command("render_scoreboard", "--check")
    assert rs.LGBM_PATH.read_text(encoding="utf-8") == lgbm_before
    assert rs.LGBM_9A1_PATH.read_text(encoding="utf-8") == lgbm_9a1_before
