"""The README scoreboard must match data/seed/scoreboard.json exactly.

The table is generated by ``manage.py render_scoreboard``; this test fails if a
refresh updated scoreboard.json but not the README (or someone hand-edited it).
"""

from __future__ import annotations

import json

from apps.forecasting.management.commands.render_scoreboard import (
    README_PATH,
    render_block,
    splice,
)
from apps.forecasting.views import SCOREBOARD_PATH


def test_readme_scoreboard_matches_artifact():
    scoreboard = json.loads(SCOREBOARD_PATH.read_text(encoding="utf-8"))
    readme = README_PATH.read_text(encoding="utf-8")
    assert splice(readme, render_block(scoreboard)) == readme, (
        "README scoreboard is stale — run `manage.py render_scoreboard`."
    )


def test_totals_are_counted_from_verdicts():
    scoreboard = {
        "eval_end": "2026-09",
        "initial_train_end": "2015-12",
        "tie_threshold": 0.02,
        "model": {"order": [1, 1, 1], "seasonal_order": [1, 1, 1, 12]},
        "groups": {
            "SUGAR": {
                "1": {"sarima_mae": 5.0, "naive_1_mae": 4.0, "rel_delta": 0.25, "verdict": "LOSES", "folds": 9},
                "3": {"sarima_mae": 4.0, "naive_1_mae": 5.0, "rel_delta": -0.2, "verdict": "BEATS", "folds": 7},
            }
        },
    }
    block = render_block(scoreboard)
    assert "beats the baseline 1, ties 0, loses 1." in block
    assert "| Sugar | 1 month | 9 | 5.000 | 4.000 | +25.0% | **loses to** the baseline |" in block
    assert "Evaluated through **2026-09**" in block
